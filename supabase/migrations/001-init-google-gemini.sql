-- Key Highlights
--  Security: The verify_student_pin function uses SECURITY DEFINER. This allows the function to bypass RLS to check the PIN hash during the login flow without exposing the student_details table to the public.
--  Sequential Integrity: The validate_punch_sequence trigger prevents "ghost hours" (like two clock-ins in a row), ensuring that the data integrity is high enough for state board audits.
--  Precision: Used NUMERIC(6, 2) for hours to ensure no floating-point math errors occur when calculating cosmetology hours (which often require precise decimal tracking).
--  Auditability: The verification_metadata JSONB column allows you to store raw data from the geofence check or facial recognition confidence scores without needing to change the table schema later.

-- 1. SETUP EXTENSIONS AND TYPES
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TYPE user_role AS ENUM ('student', 'admin');
CREATE TYPE punch_type AS ENUM ('clock_in', 'clock_out', 'break_start', 'break_end');

-- 2. CREATE CORE TABLES
-- Profile table (Extends Supabase Auth)
CREATE TABLE profiles (
  id UUID REFERENCES auth.users ON DELETE CASCADE PRIMARY KEY,
  student_id NUMERIC,
  name TEXT NOT NULL,
  role user_role DEFAULT 'student',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Student specific details (3NF separation)
CREATE TABLE student_details (
  id UUID REFERENCES profiles(id) ON DELETE CASCADE PRIMARY KEY,
  password_hash TEXT,
  pin_hash TEXT NOT NULL, -- Hashed 4-digit PIN
  required_hours NUMERIC(6, 2) DEFAULT 1500.00,
  is_active BOOLEAN DEFAULT true,
  
  -- Geofencing configuration
  home_lat DOUBLE PRECISION,
  home_long DOUBLE PRECISION,
  geofence_radius_meters INT DEFAULT 100,
  
  -- Biometric Reference (Future Use)
  face_encoding_vector VECTOR(128) -- Requires pgvector extension if used later
);

-- Time punch logs
CREATE TABLE time_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id UUID REFERENCES profiles(id) NOT NULL,
  event_type punch_type NOT NULL,
  
  -- Metadata for verification
  recorded_at TIMESTAMPTZ DEFAULT NOW(),
  punch_lat DOUBLE PRECISION,
  punch_long DOUBLE PRECISION,
  snapshot_url TEXT, -- Path to Supabase Storage bucket
  
  -- Future proofing for AI/Facial matching
  verification_metadata JSONB DEFAULT '{}'::jsonb,
  is_verified BOOLEAN DEFAULT true
);

-- 3. INDEXING FOR PERFORMANCE
CREATE INDEX idx_time_logs_student_id ON time_logs(student_id);
CREATE INDEX idx_time_logs_recorded_at ON time_logs(recorded_at);

-- 4. DATABASE FUNCTIONS & TRIGGERS

-- Function: Verify PIN via RPC (called from Edge Function)
CREATE OR REPLACE FUNCTION verify_student_pin(target_id UUID, provided_pin TEXT)
RETURNS BOOLEAN AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1 FROM student_details 
    WHERE id = target_id 
    AND pin_hash = crypt(provided_pin, pin_hash)
    AND is_active = true
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger: Enforce punch logic (e.g., can't clock in if already clocked in)
CREATE OR REPLACE FUNCTION validate_punch_sequence()
RETURNS TRIGGER AS $$
DECLARE
  last_event punch_type;
BEGIN
  SELECT event_type INTO last_event 
  FROM time_logs 
  WHERE student_id = NEW.student_id 
  ORDER BY recorded_at DESC LIMIT 1;

  -- Prevent logical errors (simplified example)
  IF NEW.event_type = 'clock_in' AND last_event = 'clock_in' THEN
    RAISE EXCEPTION 'Already clocked in.';
  ELSIF NEW.event_type = 'clock_out' AND (last_event = 'clock_out' OR last_event IS NULL) THEN
    RAISE EXCEPTION 'Cannot clock out without a clock in.';
  END IF;
  
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_validate_punch
BEFORE INSERT ON time_logs
FOR EACH ROW EXECUTE FUNCTION validate_punch_sequence();

-- 5. ROW LEVEL SECURITY (RLS) POLICIES
ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE student_details ENABLE ROW LEVEL SECURITY;
ALTER TABLE time_logs ENABLE ROW LEVEL SECURITY;

-- Admins: Global Access
CREATE POLICY "Admins have full access" ON profiles FOR ALL 
  USING (auth.jwt() ->> 'role' = 'admin');

CREATE POLICY "Admins manage student details" ON student_details FOR ALL 
  USING (auth.jwt() ->> 'role' = 'admin');

CREATE POLICY "Admins manage all logs" ON time_logs FOR ALL 
  USING (auth.jwt() ->> 'role' = 'admin');

-- Students: Read Only Access to own data
CREATE POLICY "Students can view own profile" ON profiles FOR SELECT 
  USING (auth.uid() = id);

CREATE POLICY "Students can view own logs" ON time_logs FOR SELECT 
  USING (auth.uid() = student_id);

-- 6. VIEWS FOR REPORTING
-- Real-time hour calculation
CREATE VIEW student_hours_summary AS
SELECT 
  p.id as student_id,
  p.first_name,
  p.last_name,
  sd.required_hours,
  -- Logic to sum intervals between in/out would go here
  COUNT(tl.id) FILTER (WHERE tl.event_type = 'clock_in') as total_punches
FROM profiles p
JOIN student_details sd ON p.id = sd.id
LEFT JOIN time_logs tl ON p.id = tl.student_id
WHERE p.role = 'student'
GROUP BY p.id, sd.required_hours;